    echo -e "  ${BOLD}Warnings:${NC}       ${YELLOW}${WARN_COUNT}${NC}"
    echo ""

    if [[ ${FAIL_COUNT} -eq 0 ]]; then
        echo -e "  ${BOLD}${GREEN}╔══════════════════════════════════════════╗${NC}"
        echo -e "  ${BOLD}${GREEN}║                                          ║${NC}"
        echo -e "  ${BOLD}${GREEN}║          🟢  GO FOR LAUNCH  🟢           ║${NC}"
        echo -e "  ${BOLD}${GREEN}║                                          ║${NC}"
        echo -e "  ${BOLD}${GREEN}╚══════════════════════════════════════════╝${NC}"
        echo ""

        if [[ ${WARN_COUNT} -gt 0 ]]; then
            echo -e "  ${YELLOW}⚠ ${WARN_COUNT} warning(s) — review before launch${NC}"
        fi
    else
        echo -e "  ${BOLD}${RED}╔══════════════════════════════════════════╗${NC}"
        echo -e "  ${BOLD}${RED}║                                          ║${NC}"
        echo -e "  ${BOLD}${RED}║          🔴  NO-GO — FIX FIRST  🔴       ║${NC}"
        echo -e "  ${BOLD}${RED}║                                          ║${NC}"
        echo -e "  ${BOLD}${RED}╚══════════════════════════════════════════╝${NC}"
        echo ""
        echo -e "  ${RED}${FAIL_COUNT} check(s) failed — resolve all FAIL items before launch${NC}"
    fi

    echo ""
    echo -e "  ${BOLD}Generated:$(date -u +%Y-%m-%dT%H:%M:%SZ)${NC}"
}

