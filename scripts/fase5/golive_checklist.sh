# CHECK 2: Stress Test — 1000 Players
# ═════════════════════════════════════════════════════════════════════════════
check_02_stress_test_1000() {
    header "CHECK 2/25: Stress Test — 1000 Players, 0 Crashes, RTT p95 < 100ms"

    local stress_config="${REPO_DIR}/Unreal/KhaaosRun/Source/KhaaosRun/Game/LoadTest/KhaaosStressTestConfig.h"
    if [[ -f "${stress_config}" ]]; then
        ok "Stress test framework present (KhaaosStressTestConfig)"
    else
        fail "Stress test framework missing"
    fi

    # Check for stress test results (would be generated by CI/CD)
    local results_dir="${REPO_DIR}/test-results/stress"
    if [[ -d "${results_dir}" ]]; then
        local latest_result="${results_dir}/stress_test_1000_latest.json"
        if [[ -f "${latest_result}" ]]; then
            local crashes rtt_p95 result
            crashes=$(python3 -c "import json; d=json.load(open('${latest_result}')); print(d['khaaos_stress_test']['metrics']['stability']['crash_count'])" 2>/dev/null || echo "?")
            rtt_p95=$(python3 -c "import json; d=json.load(open('${latest_result}')); print(d['khaaos_stress_test']['metrics']['rtt']['p95_ms'])" 2>/dev/null || echo "?")
            result=$(python3 -c "import json; d=json.load(open('${latest_result}')); print(d['khaaos_stress_test']['result'])" 2>/dev/null || echo "?")

            if [[ "${result}" == "PASS" ]]; then
                ok "Stress test PASSED: 1000 players, crashes=${crashes}, RTT p95=${rtt_p95}ms"
            else
                fail "Stress test FAILED: result=${result}, crashes=${crashes}, RTT p95=${rtt_p95}ms"
            fi
        else
            warn "No stress test results found — run stress test before Go Live"
        fi
    else
        warn "No stress test results directory — run stress test before Go Live"
    fi
}

