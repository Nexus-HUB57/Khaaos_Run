# ═════════════════════════════════════════════════════════════════════════════
# CHECK 5: EOS Production IDs Configured
# ═════════════════════════════════════════════════════════════════════════════
check_05_eos_production() {
    header "CHECK 5/25: EOS — Production IDs Configured, Matchmaking Live"

    local eos_config="${REGIONS_DIR}/DefaultEOS_Production.ini"
    if [[ -f "${eos_config}" ]]; then
        ok "EOS Production config present"

        # Check for production IDs (must not be empty)
        local product_id sandbox_id deployment_id
        product_id=$(rg "EOSProductId=" "${eos_config}" 2>/dev/null | head -1 | cut -d'=' -f2- | tr -d ' ')
        sandbox_id=$(rg "EOSSandboxId=" "${eos_config}" 2>/dev/null | head -1 | cut -d'=' -f2- | tr -d ' ')
        deployment_id=$(rg "EOSDeploymentId=" "${eos_config}" 2>/dev/null | head -1 | cut -d'=' -f2- | tr -d ' ')

        if [[ -n "${product_id}" && "${product_id}" != "" ]]; then
            ok "EOS Product ID configured"
        else
            fail "EOS Product ID not set — SET in DefaultEOS_Production.ini"
        fi

        if [[ -n "${sandbox_id}" && "${sandbox_id}" != "" ]]; then
            ok "EOS Sandbox ID configured"
        else
            fail "EOS Sandbox ID not set"
        fi

        if [[ -n "${deployment_id}" && "${deployment_id}" != "" ]]; then
            ok "EOS Deployment ID configured"
        else
            fail "EOS Deployment ID not set"
        fi
    else
        fail "EOS Production config missing: ${eos_config}"
    fi

    # Check matchmaking is live in all regions
    for region in "${REGIONS[@]}"; do
        if rg -q "MatchmakingPool=KR_${region^^}" "${eos_config}" 2>/dev/null; then
            ok "Matchmaking pool configured for ${region}"
        else
            fail "Matchmaking pool not configured for ${region}"
        fi
    done
}

