#!/usr/bin/env bash
# =============================================================================
# Khaaos Run — GO LIVE Final Checklist (Fase 5)
# =============================================================================
# Comprehensive pre-launch verification for production Go Live.
# Covers all checks from alpha (Fase 3) plus beta/production checks.
#
# EXIT CODES:
#   0 = GO (all checks pass)
#   1 = NO-GO (any check fails)
#
# USAGE:
#   ./golive_checklist.sh           # Run all checks, print GO/NO-GO
#   ./golive_checklist.sh --json    # Output as JSON
#   ./golive_checklist.sh --quiet   # Only show failures
#   ./golive_checklist.sh --check <n>  # Run single check by number
# =============================================================================

set -euo pipefail

# ── Colors ───────────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

# ── Logging ──────────────────────────────────────────────────────────────────────
info()  { ${QUIET} && return || echo -e "${BLUE}[INFO]${NC}  $*"; }
ok()    { echo -e "${GREEN}[PASS]${NC}  $*"; PASS_COUNT=$((PASS_COUNT + 1)); }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; WARN_COUNT=$((WARN_COUNT + 1)); }
fail()  { echo -e "${RED}[FAIL]${NC}  $*"; FAIL_COUNT=$((FAIL_COUNT + 1)); }
step()  { ${QUIET} && return || echo -e "${CYAN}${BOLD}──▶${NC} $*"; }
header() { echo -e "\n${BOLD}${CYAN}══════════════════════════════════════════════════${NC}"; echo -e "${BOLD}${CYAN}  $*${NC}"; echo -e "${BOLD}${CYAN}══════════════════════════════════════════════════${NC}"; }

# ── Constants ────────────────────────────────────────────────────────────────────
REPO_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
CONFIG_DIR="${REPO_DIR}/Unreal/KhaaosRun/Config"
REGIONS_DIR="${CONFIG_DIR}/Regions"
DOCKER_COMPOSE="${REPO_DIR}/Unreal/KhaaosRun/Build/docker-compose.yml"
PRODUCTION_COMPOSE="${REPO_DIR}/infra/deploy/docker-compose.production.yml"
SCRIPTS_ALPHA="${REPO_DIR}/scripts/alpha"

# Service endpoints
