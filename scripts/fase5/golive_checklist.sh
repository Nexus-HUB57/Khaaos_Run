# CHECK 3: Multi-Region — All 3 Regions Healthy
# ═════════════════════════════════════════════════════════════════════════════
check_03_multiregion_healthy() {
    header "CHECK 3/25: Multi-Region — All 3 Regions Healthy"

    local all_healthy=true
    for region in "${REGIONS[@]}"; do
        local health_url="http://${region}.khaaos.run:${UE5_PORT}/health"
        if http_check "${health_url}"; then
            ok "Region ${region}: HEALTHY"
        else
            # Fallback: check Docker
            if docker ps --filter "label=khaaos.region=${region}" --format "{{.Status}}" 2>/dev/null | grep -q "Up"; then
                ok "Region ${region}: HEALTHY (Docker)"
            else
                fail "Region ${region}: UNHEALTHY"
                all_healthy=false
            fi
        fi
    done

    if ${all_healthy}; then
        ok "All 3 regions healthy"
    fi
}

