ECONOMY_PORT="${ECONOMY_PORT:-3000}"
PROMETHEUS_PORT="${PROMETHEUS_PORT:-9090}"
GRAFANA_PORT="${GRAFANA_PORT:-3000}"

# Regions
REGIONS=("sa1" "na1" "eu1")
HEALTH_URLS_SA1="http://sa1.khaaos.run:${UE5_PORT}/health"
HEALTH_URLS_NA1="http://na1.khaaos.run:${UE5_PORT}/health"
HEALTH_URLS_EU1="http://eu1.khaaos.run:${UE5_PORT}/health"

# Counters
PASS_COUNT=0
FAIL_COUNT=0
WARN_COUNT=0
TOTAL_CHECKS=25

# Mode flags
QUIET=false
JSON_OUTPUT=false
SINGLE_CHECK=""

# ── Parse Arguments ──────────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
    case "$1" in
        --json)   JSON_OUTPUT=true; shift ;;
        --quiet)  QUIET=true; shift ;;
        --check)  SINGLE_CHECK="${2:-}"; shift 2 ;;
        *) shift ;;
    esac
done

# ── Helper: HTTP Check ──────────────────────────────────────────────────────────
http_check() {
    local url="$1"
    local expected_code="${2:-200}"
    local timeout="${3:-10}"
    local code
    code=$(curl -s -o /dev/null -w "%{http_code}" --max-time "${timeout}" "${url}" 2>/dev/null || echo "000")
    [[ "${code}" == "${expected_code}" ]]
}

# ── Helper: Port Check ─────────────────────────────────────────────────────────
port_check() {
    local host="$1"
    local port="$2"
    nc -z -w5 "${host}" "${port}" 2>/dev/null
}

