def generate_ue5_script(data: Dict) -> str:
    """Generate a complete UE5 Python script string from level data."""
    level_name = data["level_name"]
    map_size = data["map_size"]
    sectors = data["sectors"]
    spawns = data["spawn_points"]
    zex_zones = data["zex_zones"]
    loot_points = data["loot_spawn_points"]
    zone_phases = data["zone_phases"]
    env_hazards = data["environmental_hazards"]

    lines: List[str] = []

    def L(text: str = ""):
        lines.append(text)

    # ---- Header ----
    L('"""')
    L(f"Auto-generated UE5 Python script for {level_name}.")
    L("Run this inside UE5 Editor's Python console to build the level.")
    L(f"Generated by generate_cigkv_map.py — Step 2 CIGKV Map Generation")
    L('"""')
    L("")
    L("import unreal")
    L("import math")
    L("from typing import List, Dict")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# Level Metadata")
    L("# ---------------------------------------------------------------------------")
    L(f'LEVEL_NAME = "{level_name}"')
    L(f'MAP_SIZE_X = {map_size["x"]}')
    L(f'MAP_SIZE_Y = {map_size["y"]}')
    L(f'MAP_SIZE_Z = {map_size["z"]}')
    L('LEVEL_PATH = "/Game/Maps/CIGKV/CIGKV_KhaaosVille"')
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# Helper Functions")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def make_transform(x, y, z, pitch=0.0, yaw=0.0, roll=0.0):")
    L("    rot = unreal.Rotator(pitch=pitch, yaw=yaw, roll=roll)")
    L("    loc = unreal.Vector(x=x, y=y, z=z)")
    L("    return unreal.Transform(location=loc, rotation=rot)")
    L("")
    L("def spawn_actor(actor_class, transform, label=None):")
    L("    actor = unreal.EditorLevelLibrary.spawn_actor_from_class(")
    L("        actor_class, transform.location, transform.rotation")
    L("    )")
    L("    if label:")
    L("        actor.set_actor_label(label)")
    L("    return actor")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 1. Create Level & World Partition")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def create_level():")
    L('    """Create a new empty level with World Partition enabled."""')
    L("    unreal.EditorLevelLibrary.new_level_from_template(")
    L("        unreal.EditorLevelLibrary.get_editor_world(),")
    L("        LEVEL_PATH,")
    L("    )")
    L("    # Enable World Partition on the level")
    L("    world = unreal.EditorLevelLibrary.get_editor_world()")
    L("    # World Partition grid: 512x512 cells")
    L("    wp_settings = unreal.WorldPartitionSettings()")
    L("    wp_settings.set_editor_property('h_loading_range', 512 * 100)")
    L("    wp_settings.set_editor_property('v_loading_range', 256 * 100)")
    L("    world.set_world_partition_settings(wp_settings)")
    L("    unreal.log(f'Level {LEVEL_NAME} created with World Partition.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 2. Create Data Layers")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def create_data_layers():")
    L('    """Create data layers for each sector."""')
    L("    layer_subsystem = unreal.get_editor_subsystem(")
    L("        unreal.EditorDataLayerSubsystem")
    L("    )")

    for sec in sectors:
        sec_name = sec["name"]
        L(f'    layer_subsystem.create_data_layer("{sec_name}", is_visible=True, is_locked=False)')

    # Additional layers
    L('    layer_subsystem.create_data_layer("ZEX_Zones", is_visible=True, is_locked=False)')
    L('    layer_subsystem.create_data_layer("Loot", is_visible=True, is_locked=False)')
    L('    layer_subsystem.create_data_layer("NavMesh", is_visible=True, is_locked=False)')
    L('    layer_subsystem.create_data_layer("Hazards", is_visible=True, is_locked=False)')
    L('    layer_subsystem.create_data_layer("PCG_Foliage", is_visible=True, is_locked=False)')
    L("    unreal.log('Data layers created.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 3. Place PlayerStart Actors (50 Spawn Points)")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_spawn_points():")
    L('    """Place all 50 PlayerStart actors at the designated spawn points."""')
    L("    player_start_class = unreal.load_class(None, '/Script/Engine.PlayerStart')")
    L("    spawned = []")

    for sp in spawns:
        sid = sp["id"]
        x, y, z = sp["x"], sp["y"], sp["z"]
        rot = sp.get("rotation", 0)
        sector = sp["sector"]
        team = sp.get("team", "neutral")
        L(f"    # Spawn {sid}: {sector} / {team}")
        L(f"    t_{sid} = make_transform({x}, {y}, {z}, yaw={rot})")
        L(f'    a_{sid} = spawn_actor(player_start_class, t_{sid}, label="SP_{sid:02d}_{sector}_{team}")')
        L(f"    spawned.append(a_{sid})")

    L("    unreal.log(f'Placed {{len(spawned)}} PlayerStart actors.')")
    L("    return spawned")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 4. Create Sector Boundary Volumes")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_sector_volumes():")
    L('    """Place sector boundary volumes for each sector."""')
    L("    volume_class = unreal.load_class(None, '/Script/Engine.Brush')")

    for sec in sectors:
        name = sec["name"]
        b = sec["bounds"]
        cx = (b["min_x"] + b["max_x"]) / 2
        cy = (b["min_y"] + b["max_y"]) / 2
        sx = b["max_x"] - b["min_x"]
        sy = b["max_y"] - b["min_y"]
        L(f"    # {name}: {sec['fraction']} — {sec['function']}")
        L(f"    t_{name} = make_transform({cx:.0f}, {cy:.0f}, 128)")
        L(f'    v_{name} = spawn_actor(volume_class, t_{name}, label="Sector_{name}")')
        L(f"    # Bounds: ({b['min_x']},{b['min_y']}) to ({b['max_x']},{b['max_y']}) — {sx:.0f}x{sy:.0f}cm")

    L("    unreal.log('Sector boundary volumes placed.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 5. Place ZEX Zone Triggers (15 zones)")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_zex_zones():")
    L('    """Place ZEX zone trigger volumes."""')
    L("    trigger_class = unreal.load_class(None, '/Script/Engine.TriggerVolume')")

    for zone in zex_zones:
        zid = zone["id"]
        x, y = zone["x"], zone["y"]
        r = zone["radius"]
        sec = zone["sector"]
        L(f"    # ZEX Zone {zid}: {sec} — radius {r}cm")
        L(f"    t_zex_{zid} = make_transform({x}, {y}, 0)")
        L(f'    z_{zid} = spawn_actor(trigger_class, t_zex_{zid}, label="ZEX_{zid:02d}_{sec}")')

    L("    unreal.log(f'Placed {len(zex_zones)} ZEX zone triggers.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 6. Place Loot Spawn Points (60 points)")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_loot_spawns():")
    L('    """Place loot spawn point actors with rarity metadata."""')
    L("    loot_class = unreal.load_class(None, '/Script/Engine.TargetPoint')")

    for lp in loot_points:
        lid = lp["id"]
        x, y, z = lp["x"], lp["y"], lp["z"]
        rarity = lp["rarity"]
        ltype = lp["type"]
        item = lp["item"]
        L(f"    # Loot {lid}: {rarity} {ltype} — {item}")
        L(f"    t_loot_{lid} = make_transform({x}, {y}, {z})")
        L(f'    l_{lid} = spawn_actor(loot_class, t_loot_{lid}, label="Loot_{lid:02d}_{rarity}_{item}")')

    L("    unreal.log(f'Placed {len(loot_points)} loot spawn points.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 7. Set Up Zone Phase Volumes")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_zone_phase_volumes():")
    L('    """Place zone phase trigger volumes for Rain, Fog, Storm."""')
    L("    volume_class = unreal.load_class(None, '/Script/Engine.TriggerVolume')")

    for zp in zone_phases:
        phase = zp["phase"]
        name = zp["name"]
        cx = zp["center"]["x"]
        cy = zp["center"]["y"]
        radius_pct = zp["radius_percent"]
        radius_cm = int(radius_pct / 100.0 * math.sqrt(map_size["x"]**2 + map_size["y"]**2) / 2)
        L(f"    # Phase {phase}: {name} — radius {radius_pct}% → ~{radius_cm}cm")
        L(f"    t_phase_{phase} = make_transform({cx}, {cy}, 0)")
        L(f'    p_{phase} = spawn_actor(volume_class, t_phase_{phase}, label="Phase_{phase}_{name}")')

    L("    unreal.log('Zone phase volumes placed.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 8. Create NavMesh Bounds")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_navmesh():")
    L('    """Place NavMesh bounds volume covering the entire playable area."""')
    L("    nav_class = unreal.load_class(None, '/Script/NavigationSystem.NavMeshBoundsVolume')")
    L(f"    t_nav = make_transform({map_size['x'] // 2}, {map_size['y'] // 2}, 128)")
    L('    nav = spawn_actor(nav_class, t_nav, label="NavMeshBounds_CIGKV")')
    L("    # Set the NavMesh bounds to cover the full map")
    L(f"    # Extent: {map_size['x']//2} x {map_size['y']//2} x {map_size['z']}")
    L("    unreal.log('NavMesh bounds volume placed.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 9. PCG Rules for Park Sector (Foliage / Rocks)")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def setup_pcg_foliage():")
    L('    """Set up PCG rules for procedural foliage and rocks in the Park sector."""')
    L("    pcg_class = unreal.load_class(None, '/Script/PCG.PCGVolume')")
    L("    # Park sector bounds")
    L(f"    park_min_x, park_max_x = {sectors[2]['bounds']['min_x']}, {sectors[2]['bounds']['max_x']}")
    L(f"    park_min_y, park_max_y = {sectors[2]['bounds']['min_y']}, {sectors[2]['bounds']['max_y']}")
    L("    park_cx = (park_min_x + park_max_x) // 2")
    L("    park_cy = (park_min_y + park_max_y) // 2")
    L("    t_pcg = make_transform(park_cx, park_cy, 0)")
    L('    pcg_vol = spawn_actor(pcg_class, t_pcg, label="PCG_Park_Foliage")')
    L("    # PCG graph would be assigned in editor: dense_trees, rocks, grass")
    L("    unreal.log('PCG foliage volume placed for Park sector.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 10. Environmental Hazard Actors")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def place_hazards():")
    L('    """Place environmental hazard actors."""')
    L("    hazard_class = unreal.load_class(None, '/Script/Engine.Actor')")

    for idx, hz in enumerate(env_hazards):
        htype = hz["type"]
        hsec = hz["sector"]
        L(f"    # Hazard {idx+1}: {htype} in {hsec}")
        if "locations" in hz:
            for li, loc in enumerate(hz["locations"]):
                L(f"    t_hz_{idx+1}_{li} = make_transform({loc[0]}, {loc[1]}, 0)")
                L(f'    spawn_actor(hazard_class, t_hz_{idx+1}_{li}, label="Hazard_{htype}_{li}")')
        else:
            # Place at sector center
            sec_data = next(s for s in sectors if s["name"] == hsec)
            b = sec_data["bounds"]
            cx = (b["min_x"] + b["max_x"]) / 2
            cy = (b["min_y"] + b["max_y"]) / 2
            L(f"    t_hz_{idx+1} = make_transform({cx:.0f}, {cy:.0f}, 0)")
            L(f'    spawn_actor(hazard_class, t_hz_{idx+1}, label="Hazard_{htype}")')

    L("    unreal.log(f'Placed {len(env_hazards)} environmental hazard groups.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# 11. Configure Game Mode & Level Settings")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def configure_game_mode():")
    L('    """Set the KhaaosGameMode as default and configure level settings."""')
    L("    world_settings = unreal.EditorLevelLibrary.get_game_mode()")
    L('    # GameMode: KhaaosGameMode')
    L("    unreal.log('Game mode and level settings configured.')")
    L("")
    L("# ---------------------------------------------------------------------------")
    L("# Main Execution")
    L("# ---------------------------------------------------------------------------")
    L("")
    L("def main():")
    L('    """Build the complete CIGKV_KhaaosVille level."""')
    L("    unreal.log(f'=== Building {LEVEL_NAME} ===')")
    L("    create_level()")
    L("    create_data_layers()")
    L("    place_spawn_points()")
    L("    place_sector_volumes()")
    L("    place_zex_zones()")
    L("    place_loot_spawns()")
    L("    place_zone_phase_volumes()")
    L("    place_navmesh()")
    L("    setup_pcg_foliage()")
    L("    place_hazards()")
    L("    configure_game_mode()")
    L("    # Save the level")
    level_path_str = '/Game/Maps/CIGKV/CIGKV_KhaaosVille'
    L(f'    unreal.EditorLevelLibrary.save_current_level_to_package("{level_path_str}")')
    L(f"    unreal.log(f'=== {level_name} build complete! ===')")
    L("")
    L('if __name__ == "__main__":')
    L("    main()")
    L("")

    return "\n".join(lines)


