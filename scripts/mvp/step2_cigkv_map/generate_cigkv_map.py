def generate_visualization(data: Dict, output_path: Path) -> None:
    """Generate a top-down PNG map visualization using matplotlib."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.patches as mpatches
        from matplotlib.font_manager import FontProperties
    except ImportError:
        print("WARNING: matplotlib not installed — skipping visualization.", file=sys.stderr)
        return

    # Try to use Noto Sans SC for Portuguese/Chinese text
    try:
        font_path = Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
        if not font_path.exists():
            font_path = Path("/usr/share/fonts/truetype/noto/NotoSansSC-Regular.ttf")
        if font_path.exists():
            fp = FontProperties(fname=str(font_path))
        else:
            fp = FontProperties()
    except Exception:
        fp = FontProperties()

    map_x = data["map_size"]["x"]
    map_y = data["map_size"]["y"]
    sectors = data["sectors"]
    spawns = data["spawn_points"]
    zex_zones = data["zex_zones"]
    loot_points = data["loot_spawn_points"]
    zone_phases = data["zone_phases"]
    env_hazards = data["environmental_hazards"]

    SECTOR_COLORS = {
        "ArmoryHub": "#2ecc71",
        "ProvingGrounds": "#e67e22",
        "Park": "#3498db",
    }

    RARITY_COLORS = {
        "common": "#aaaaaa",
        "uncommon": "#2ecc71",
        "rare": "#3498db",
        "epic": "#9b59b6",
        "legendary": "#f1c40f",
    }

    fig, ax = plt.subplots(1, 1, figsize=(14, 14), constrained_layout=True)
    ax.set_xlim(0, map_x)
    ax.set_ylim(0, map_y)
    ax.set_aspect("equal")
    ax.set_xlabel("X (cm)", fontsize=10)
    ax.set_ylabel("Y (cm)", fontsize=10)
    ax.set_title("CIGKV KhaaosVille — Top-Down Map Layout", fontsize=14, fontweight="bold")

    # Draw sector backgrounds
    for sec in sectors:
        name = sec["name"]
        b = sec["bounds"]
        color = SECTOR_COLORS.get(name, "#cccccc")
        rect = mpatches.Rectangle(
            (b["min_x"], b["min_y"]),
            b["max_x"] - b["min_x"],
            b["max_y"] - b["min_y"],
            linewidth=2, edgecolor="black", facecolor=color, alpha=0.2,
            label=f"{name} ({sec['fraction']})"
        )
        ax.add_patch(rect)
        # Sector label
        cx = (b["min_x"] + b["max_x"]) / 2
        cy = (b["min_y"] + b["max_y"]) / 2
        ax.text(cx, cy, f"{name}\n({sec['fraction']})",
                ha="center", va="center", fontsize=12, fontweight="bold",
                alpha=0.5, fontproperties=fp)

    # Draw zone phase circles
    for zp in zone_phases[1:]:  # skip phase 1 (Clear)
        cx, cy = zp["center"]["x"], zp["center"]["y"]
        pct = zp["radius_percent"] / 100.0
        radius = pct * math.sqrt(map_x**2 + map_y**2) / 2
        circle = mpatches.Circle(
            (cx, cy), radius, linewidth=1.5,
            edgecolor="red", facecolor="none", linestyle="--",
            label=f"Phase {zp['phase']}: {zp['name']} ({zp['radius_percent']}%)"
        )
        ax.add_patch(circle)

    # Draw ZEX zones
    for zone in zex_zones:
        circle = mpatches.Circle(
            (zone["x"], zone["y"]), zone["radius"],
            linewidth=1, edgecolor="red", facecolor="red", alpha=0.3
        )
        ax.add_patch(circle)
        ax.text(zone["x"], zone["y"], f"Z{zone['id']}", fontsize=6,
                ha="center", va="center", color="darkred", fontweight="bold")

    # Draw environmental hazard markers
    hazard_markers = {
        "acid_rain": ("X", "yellow"),
        "hallucinogenic_fog": ("X", "purple"),
        "carnivorous_flora": ("X", "green"),
        "collapsing_structure": ("X", "orange"),
    }
    for hz in env_hazards:
        marker, color = hazard_markers.get(hz["type"], ("X", "red"))
        if "locations" in hz:
            for loc in hz["locations"]:
                ax.plot(loc[0], loc[1], marker=marker, markersize=10, color=color, markeredgecolor="black")
        else:
            # Place at sector center
            sec = next(s for s in sectors if s["name"] == hz["sector"])
            b = sec["bounds"]
            cx = (b["min_x"] + b["max_x"]) / 2
            cy = (b["min_y"] + b["max_y"]) / 2
            ax.plot(cx, cy, marker=marker, markersize=12, color=color, markeredgecolor="black")

    # Draw loot spawn points as diamonds
    for lp in loot_points:
        color = RARITY_COLORS.get(lp["rarity"], "gray")
        ax.plot(lp["x"], lp["y"], marker="D", markersize=5, color=color,
                markeredgecolor="black", markeredgewidth=0.5)

    # Draw spawn points as numbered dots
    for sp in spawns:
        color = SECTOR_COLORS.get(sp["sector"], "gray")
        ax.plot(sp["x"], sp["y"], "o", markersize=7, color=color,
                markeredgecolor="black", markeredgewidth=0.8)
        ax.text(sp["x"] + 30, sp["y"] + 30, str(sp["id"]), fontsize=6, color="black")

    # Legend
    legend_handles = [
        mpatches.Patch(color=SECTOR_COLORS["ArmoryHub"], alpha=0.4, label="ArmoryHub (1/8)"),
        mpatches.Patch(color=SECTOR_COLORS["ProvingGrounds"], alpha=0.4, label="ProvingGrounds (3/8)"),
        mpatches.Patch(color=SECTOR_COLORS["Park"], alpha=0.4, label="Park (4/8)"),
        plt.Line2D([0], [0], marker="o", color="w", markerfacecolor="gray", markersize=8, label="Spawn Points (50)"),
        plt.Line2D([0], [0], marker="o", color="w", markerfacecolor="red", markersize=8, alpha=0.5, label="ZEX Zones (15)"),
        plt.Line2D([0], [0], marker="D", color="w", markerfacecolor="gray", markersize=6, label="Loot Points (60)"),
        plt.Line2D([0], [0], linestyle="--", color="red", label="Zone Phases"),
    ]
    # Rarity legend
    for rarity, color in RARITY_COLORS.items():
        legend_handles.append(
            plt.Line2D([0], [0], marker="D", color="w", markerfacecolor=color,
                       markersize=6, label=f"Loot: {rarity}")
        )

    ax.legend(handles=legend_handles, loc="upper left", fontsize=8, framealpha=0.9)

