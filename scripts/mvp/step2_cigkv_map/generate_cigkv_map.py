def load_level_data(path: Path) -> Dict[str, Any]:
    """Load and return the CIGKV level data JSON."""
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def dist2d(p1: Dict, p2: Dict) -> float:
    """Euclidean distance in the XY plane (cm)."""
    return math.sqrt((p1["x"] - p2["x"]) ** 2 + (p1["y"] - p2["y"]) ** 2)


def point_in_sector(x: float, y: float, sector: Dict) -> bool:
    """Check if a point lies within a sector's 2D bounds."""
    b = sector["bounds"]
    return b["min_x"] <= x <= b["max_x"] and b["min_y"] <= y <= b["max_y"]


def validate_spawn_points(data: Dict) -> Tuple[bool, List[str]]:
    """Validate all spawn points: spacing, bounds, sector membership."""
    errors: List[str] = []
    map_x = data["map_size"]["x"]
    map_y = data["map_size"]["y"]
    sectors = {s["name"]: s for s in data["sectors"]}
    spawns = data["spawn_points"]
    MIN_SPACING = 500  # cm

    # 1. Minimum spacing
    for i in range(len(spawns)):
        for j in range(i + 1, len(spawns)):
            d = dist2d(spawns[i], spawns[j])
            if d < MIN_SPACING:
                errors.append(
                    f"Spawn {spawns[i]['id']} and {spawns[j]['id']} are only "
                    f"{d:.0f}cm apart (min {MIN_SPACING}cm)"
                )

    # 2. Map bounds
    for sp in spawns:
        if not (0 <= sp["x"] <= map_x and 0 <= sp["y"] <= map_y):
            errors.append(
                f"Spawn {sp['id']} at ({sp['x']},{sp['y']}) is outside map bounds "
                f"(0-{map_x}, 0-{map_y})"
            )

    # 3. Sector membership
    for sp in spawns:
        sec = sectors.get(sp["sector"])
        if sec is None:
            errors.append(f"Spawn {sp['id']} references unknown sector '{sp['sector']}'")
            continue
        if not point_in_sector(sp["x"], sp["y"], sec):
            errors.append(
                f"Spawn {sp['id']} at ({sp['x']},{sp['y']}) is outside its sector "
                f"'{sp['sector']}' bounds"
            )

    # 4. Distribution
    sector_counts: Dict[str, int] = {}
    for sp in spawns:
        sector_counts[sp["sector"]] = sector_counts.get(sp["sector"], 0) + 1
    expected = {"ArmoryHub": 5, "ProvingGrounds": 20, "Park": 25}
    for sec_name, exp_count in expected.items():
        actual = sector_counts.get(sec_name, 0)
        if actual != exp_count:
            errors.append(
                f"Sector '{sec_name}' has {actual} spawns, expected {exp_count}"
            )

    ok = len(errors) == 0
    return ok, errors


