#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════
# Khaaos Run — EOS Production Setup (Epic Online Services)
# Registers and configures all 5 EOS subsystems for production
# ═══════════════════════════════════════════════════════════════════════
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
EOS_CONFIG_DIR="${REPO_ROOT}/config/eos"
UNREAL_CONFIG="${REPO_ROOT}/Unreal/KhaaosRun/Config"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
log()  { echo -e "${GREEN}[✓]${NC} $*"; }
warn() { echo -e "${YELLOW}[⚠]${NC} $*"; }
err()  { echo -e "${RED}[✗]${NC} $*"; }
info() { echo -e "${CYAN}[→]${NC} $*"; }

mkdir -p "${EOS_CONFIG_DIR}"

# ─── Step 1: Epic Dev Portal Registration ───
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "  KHAAOS RUN — EOS Production Setup"
echo "═══════════════════════════════════════════════════════════"
echo ""
echo "This script configures Epic Online Services for production."
echo "You need an Epic Dev Portal account (https://dev.epicgames.com)"
echo ""

# Check for existing credentials
if [ -f "${EOS_CONFIG_DIR}/eos_production.env" ]; then
  log "Found existing EOS configuration"
  source "${EOS_CONFIG_DIR}/eos_production.env"
fi

# Prompt for credentials if not set
if [ -z "${EOS_PRODUCT_ID:-}" ]; then
  echo "━━━ Step 1: Epic Dev Portal Registration ━━━"
  echo ""
  echo "1. Go to https://dev.epicgames.com/portal"
  echo "2. Create a new Product: 'Khaaos Run'"
  echo "3. Create a Sandbox: 'Production'"
  echo "4. Create a Deployment: 'Live'"
  echo "5. Note down the IDs below:"
  echo ""
  read -rp "EOS Product ID: " EOS_PRODUCT_ID
  read -rp "EOS Sandbox ID: " EOS_SANDBOX_ID
  read -rp "EOS Deployment ID: " EOS_DEPLOYMENT_ID
  read -rp "EOS Client ID: " EOS_CLIENT_ID
  read -rp "EOS Client Secret: " EOS_CLIENT_SECRET
  read -rp "EOS Encryption Key (64-char hex): " EOS_ENCRYPTION_KEY
fi

# Save credentials
cat > "${EOS_CONFIG_DIR}/eos_production.env" << EOF
# EOS Production Credentials — DO NOT COMMIT TO GIT
# Generated by setup_eos_production_full.sh
EOS_PRODUCT_ID=${EOS_PRODUCT_ID}
EOS_SANDBOX_ID=${EOS_SANDBOX_ID}
EOS_DEPLOYMENT_ID=${EOS_DEPLOYMENT_ID}
EOS_CLIENT_ID=${EOS_CLIENT_ID}
EOS_CLIENT_SECRET=${EOS_CLIENT_SECRET}
EOS_ENCRYPTION_KEY=${EOS_ENCRYPTION_KEY}
EOF

chmod 600 "${EOS_CONFIG_DIR}/eos_production.env"
log "Credentials saved to ${EOS_CONFIG_DIR}/eos_production.env"

# ─── Step 2: Configure 5 EOS Subsystems ───
info "Step 2: Configuring 5 EOS Subsystems..."

# 2.1 Auth Configuration
cat > "${EOS_CONFIG_DIR}/eos_auth.json" << EOF
{
  "subsystem": "Auth",
  "product_id": "${EOS_PRODUCT_ID}",
  "sandbox_id": "${EOS_SANDBOX_ID}",
  "deployment_id": "${EOS_DEPLOYMENT_ID}",
  "client_id": "${EOS_CLIENT_ID}",
  "client_secret": "${EOS_CLIENT_SECRET}",
  "encryption_key": "${EOS_ENCRYPTION_KEY}",
  "auth_flags": [
    "EAS_NoDeleteInvalidAuthSession",
    "EAS_RequirePlatformAuth"
  ],
  "token_refresh_interval_seconds": 3600,
  "device_auth_enabled": true,
  "external_auth_providers": ["Epic", "DeviceId"],
  "max_login_attempts_per_minute": 10
}
EOF
log "Auth configuration written"

# 2.2 Lobby Configuration
cat > "${EOS_CONFIG_DIR}/eos_lobby.json" << EOF
{
  "subsystem": "Lobby",
  "product_id": "${EOS_PRODUCT_ID}",
  "sandbox_id": "${EOS_SANDBOX_ID}",
  "deployment_id": "${EOS_DEPLOYMENT_ID}",
  "max_lobbies_per_player": 1,
  "max_members_per_lobby": 64,
  "lobby_search_timeout_seconds": 30,
  "attributes": [
    {"key": "world", "type": "string", "values": ["CIGKV", "W1_Barburhen", "W2_Priadus", "W3_Ckesalth", "W4_Arukheea"]},
    {"key": "rank_tier", "type": "int64", "range": [0, 100]},
    {"key": "region", "type": "string", "values": ["sa-east-1", "us-east-1", "eu-west-1"]},
    {"key": "game_mode", "type": "string", "values": ["solo", "duo", "squad"]}
  ],
  "rtt_poll_interval_ms": 1000,
  "max_search_results": 50
}
EOF
log "Lobby configuration written"

# 2.3 Matchmaking Configuration
cat > "${EOS_CONFIG_DIR}/eos_matchmaking.json" << EOF
{
  "subsystem": "Matchmaking",
  "product_id": "${EOS_PRODUCT_ID}",
  "sandbox_id": "${EOS_SANDBOX_ID}",
  "deployment_id": "${EOS_DEPLOYMENT_ID}",
  "pools": [
    {
      "name": "CIGKV_Training",
      "world": "CIGKV",
      "max_players": 50,
      "skill_tiers": ["Unranked", "Bronze", "Silver"],
      "timeout_seconds": 60,
      "backfill_enabled": true
    },
    {
      "name": "W1_Barburhen_Solo",
      "world": "W1_Barburhen",
      "max_players": 100,
      "skill_tiers": ["Bronze", "Silver", "Gold", "Platinum", "Diamond"],
      "timeout_seconds": 45,
      "backfill_enabled": true
    },
    {
      "name": "W2_Priadus_Solo",
      "world": "W2_Priadus",
      "max_players": 75,
      "skill_tiers": ["Silver", "Gold", "Platinum", "Diamond"],
      "timeout_seconds": 45,
      "backfill_enabled": true
    },
    {
      "name": "W3_Ckesalth_Solo",
      "world": "W3_Ckesalth",
      "max_players": 60,
      "skill_tiers": ["Gold", "Platinum", "Diamond"],
      "timeout_seconds": 60,
      "backfill_enabled": false
    },
    {
      "name": "W4_Arukheea_Solo",
      "world": "W4_Arukheea",
      "max_players": 80,
      "skill_tiers": ["Gold", "Platinum", "Diamond"],
      "timeout_seconds": 60,
      "backfill_enabled": true
    }
  ],
  "mmr_algorithm": "TrueSkill2",
  "match_completion_timeout_seconds": 300
}
EOF
log "Matchmaking configuration written"

# 2.4 Sessions Configuration
cat > "${EOS_CONFIG_DIR}/eos_sessions.json" << EOF
{
  "subsystem": "Sessions",
  "product_id": "${EOS_PRODUCT_ID}",
  "sandbox_id": "${EOS_SANDBOX_ID}",
  "deployment_id": "${EOS_DEPLOYMENT_ID}",
  "session_timeout_minutes": 60,
  "heartbeat_interval_seconds": 30,
  "max_sessions_per_server": 4,
  "session_properties": [
    "world_name", "game_mode", "current_players",
    "max_players", "zone_phase", "server_version",
    "region", "is_dedicated"
  ],
  "presence_enabled": true,
  "presence_update_interval_seconds": 15,
  "invite_timeout_seconds": 300
}
EOF
log "Sessions configuration written"

# 2.5 Cloud Save Configuration
cat > "${EOS_CONFIG_DIR}/eos_cloudsave.json" << EOF
{
  "subsystem": "CloudSave",
  "product_id": "${EOS_PRODUCT_ID}",
  "sandbox_id": "${EOS_SANDBOX_ID}",
  "deployment_id": "${EOS_DEPLOYMENT_ID}",
  "compression": "LZ4",
  "integrity_hash": "SHA256",
  "max_key_size_bytes": 102400,
  "max_value_size_bytes": 10485760,
  "auto_save_interval_seconds": 120,
  "sync_on_session_end": true,
  "conflict_resolution": "server_wins",
  "buckets": [
    {"name": "player_progress", "max_keys": 100},
    {"name": "inventory",       "max_keys": 500},
    {"name": "settings",        "max_keys": 50},
    {"name": "war_i_state",     "max_keys": 20}
  ]
}
EOF
log "Cloud Save configuration written"

# ─── Step 3: Region Manager Configuration ───
info "Step 3: Configuring 3 regions..."

cat > "${EOS_CONFIG_DIR}/eos_regions.json" << EOF
{
  "regions": [
    {
      "id": "sa-east-1",
      "name": "São Paulo",
      "country": "BR",
      "latency_weight": 1.0,
      "dedicated_server_port": 7777,
      "beacon_port": 15000,
      "matchmaking_pool": ["CIGKV_Training", "W1_Barburhen_Solo"],
      "active": true
    },
    {
      "id": "us-east-1",
      "name": "North Virginia",
      "country": "US",
      "latency_weight": 0.8,
      "dedicated_server_port": 7777,
      "beacon_port": 15000,
      "matchmaking_pool": ["W1_Barburhen_Solo", "W2_Priadus_Solo"],
      "active": true
    },
    {
      "id": "eu-west-1",
      "name": "Ireland",
      "country": "IE",
      "latency_weight": 0.8,
      "dedicated_server_port": 7777,
      "beacon_port": 15000,
      "matchmaking_pool": ["W3_Ckesalth_Solo", "W4_Arukheea_Solo"],
      "active": true
    }
  ],
  "routing_policy": "latency_based",
  "failover_enabled": true,
  "max_cross_region_latency_ms": 150
}
EOF
log "Region configuration written"

# ─── Step 4: Write UE5 INI Configs ───
info "Step 4: Writing UE5 INI configurations..."

cat > "${UNREAL_CONFIG}/Regions/DefaultEOS_Production.ini" << EOF
[EOSProduction]
ProductID=${EOS_PRODUCT_ID}
SandboxID=${EOS_SANDBOX_ID}
DeploymentID=${EOS_DEPLOYMENT_ID}
ClientID=${EOS_CLIENT_ID}
ClientSecret=${EOS_CLIENT_SECRET}
EncryptionKey=${EOS_ENCRYPTION_KEY}

[EOSProduction.Auth]
AuthFlags=EAS_NoDeleteInvalidAuthSession,EAS_RequirePlatformAuth
TokenRefreshInterval=3600
DeviceAuthEnabled=true
MaxLoginAttempts=10

[EOSProduction.Lobby]
MaxLobbiesPerPlayer=1
MaxMembersPerLobby=64
SearchTimeout=30
RTTPollInterval=1000

[EOSProduction.Matchmaking]
Algorithm=TrueSkill2
MatchTimeout=60
BackfillEnabled=true

[EOSProduction.Sessions]
SessionTimeout=60
HeartbeatInterval=30
MaxSessionsPerServer=4
PresenceEnabled=true

[EOSProduction.CloudSave]
Compression=LZ4
IntegrityHash=SHA256
MaxKeySize=102400
AutoSaveInterval=120
SyncOnSessionEnd=true

[EOSProduction.Regions]
+Region=sa-east-1,São Paulo,BR,7777,15000,1.0
+Region=us-east-1,North Virginia,US,7777,15000,0.8
+Region=eu-west-1,Ireland,IE,7777,15000,0.8
RoutingPolicy=latency_based
FailoverEnabled=true
MaxCrossRegionLatency=150
EOF
log "UE5 INI configuration written"

# ─── Step 5: Validation ───
info "Step 5: Validating EOS configuration..."

PASS=0; FAIL=0

# Check all config files exist
for f in eos_auth.json eos_lobby.json eos_matchmaking.json eos_sessions.json eos_cloudsave.json eos_regions.json; do
  if [ -f "${EOS_CONFIG_DIR}/${f}" ]; then
    log "Config OK: ${f}"
    ((PASS++))
  else
    err "Missing: ${f}"
    ((FAIL++))
  fi
done

# Check UE5 INI
if [ -f "${UNREAL_CONFIG}/Regions/DefaultEOS_Production.ini" ]; then
  log "UE5 INI OK"
  ((PASS++))
else
  err "UE5 INI missing"
  ((FAIL++))
fi

# Check credential file permissions
if [ "$(stat -c '%a' "${EOS_CONFIG_DIR}/eos_production.env" 2>/dev/null || echo '000')" = "600" ]; then
  log "Credentials file permissions OK (600)"
  ((PASS++))
else
  warn "Credentials file should have 600 permissions"
  ((FAIL++))
fi

# Validate JSON
for f in "${EOS_CONFIG_DIR}"/*.json; do
  if python3 -c "import json; json.load(open('${f}'))" 2>/dev/null; then
    log "Valid JSON: $(basename "${f}")"
    ((PASS++))
  else
    err "Invalid JSON: $(basename "${f}")"
    ((FAIL++))
  fi
done

# ─── Summary ───
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "  EOS PRODUCTION SETUP — COMPLETE"
echo "═══════════════════════════════════════════════════════════"
echo "  Subsystems:   Auth ✅ | Lobby ✅ | Matchmaking ✅ | Sessions ✅ | CloudSave ✅"
echo "  Regions:      sa-east-1 ✅ | us-east-1 ✅ | eu-west-1 ✅"
echo "  Match Pools:  5 (CIGKV, W1, W2, W3, W4)"
echo "  Validation:   ${PASS} PASS / ${FAIL} FAIL"
echo "  Credentials:  ${EOS_CONFIG_DIR}/eos_production.env"
echo "═══════════════════════════════════════════════════════════"
echo ""
echo "Next steps:"
echo "  1. Add eos_production.env to .gitignore (contains secrets)"
echo "  2. Set EOS env vars in CI/CD: GitHub Secrets"
echo "  3. Test EOS Auth: run scripts/fase2/validate_eos_auth.sh"
echo "  4. Deploy dedicated server with EOS integration enabled"
