#!/bin/bash
# ═══════════════════════════════════════════════════════════════════════
# Khaaos Run — Build-Ready Verification Script
# Validates all 4 steps are in place for UE5 compilation
# ═══════════════════════════════════════════════════════════════════════
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PASS=0; FAIL=0; WARN=0

GREEN='\033[0;32m'; RED='\033[0;31m'; YELLOW='\033[1;33m'; NC='\033[0m'
ok()   { echo -e "  ${GREEN}✓${NC} $1"; ((PASS++)); }
fail() { echo -e "  ${RED}✗${NC} $1"; ((FAIL++)); }
warn() { echo -e "  ${YELLOW}⚠${NC} $1"; ((WARN++)); }

echo ""
echo "═══════════════════════════════════════════════════════════"
echo "  KHAAOS RUN — Build-Ready Verification"
echo "═══════════════════════════════════════════════════════════"

# ─── Step 1: UE5 Build Infrastructure ───
echo ""
echo "━━━ Step 1: UE5 Build Infrastructure ━━━"

if [ -f "${REPO_ROOT}/infra/terraform/modules/build-vm/main.tf" ]; then
  ok "Terraform build-vm module exists"
else fail "Missing: infra/terraform/modules/build-vm/main.tf"; fi

if [ -f "${REPO_ROOT}/infra/terraform/modules/build-vm/user-data.sh.tpl" ]; then
  ok "Build VM user-data cloud-init exists"
else fail "Missing: user-data.sh.tpl"; fi

if [ -f "${REPO_ROOT}/scripts/build/setup_ue5_full.sh" ]; then
  ok "UE5 full setup script exists"
  if grep -q "Phase 7" "${REPO_ROOT}/scripts/build/setup_ue5_full.sh"; then
    ok "Setup script has 7 phases (complete)"
  else fail "Setup script incomplete (missing phases)"; fi
else fail "Missing: scripts/build/setup_ue5_full.sh"; fi

# ─── Step 2: CIGKV Level Definition ───
echo ""
echo "━━━ Step 2: CIGKV Level Definition ━━━"

LEVEL_JSON="${REPO_ROOT}/config/levels/CIGKV_level_data.json"
if [ -f "${LEVEL_JSON}" ]; then
  ok "CIGKV level JSON exists"
  
  # Validate JSON
  if python3 -c "import json; json.load(open('${LEVEL_JSON}'))" 2>/dev/null; then
    ok "CIGKV level JSON is valid"
  else fail "CIGKV level JSON is invalid"; fi
  
  # Check spawn points count
  SPAWNS=$(python3 -c "import json; d=json.load(open('${LEVEL_JSON}')); print(len(d['spawn_points']))" 2>/dev/null || echo 0)
  if [ "$SPAWNS" -ge 50 ]; then
    ok "Spawn points: ${SPAWNS} (≥50 required)"
  else fail "Spawn points: ${SPAWNS} (<50 required)"; fi
  
  # Check ZEX count
  ZEX=$(python3 -c "import json; d=json.load(open('${LEVEL_JSON}')); print(len(d['zex_zones']))" 2>/dev/null || echo 0)
  if [ "$ZEX" -ge 15 ]; then
    ok "ZEX zones: ${ZEX} (≥15 required)"
  else fail "ZEX zones: ${ZEX} (<15 required)"; fi
  
  # Check loot count
  LOOT=$(python3 -c "import json; d=json.load(open('${LEVEL_JSON}')); print(len(d['loot_spawn_points']))" 2>/dev/null || echo 0)
  if [ "$LOOT" -ge 60 ]; then
    ok "Loot points: ${LOOT} (≥60 required)"
  else fail "Loot points: ${LOOT} (<60 required)"; fi
  
  # Check zone phases
  ZONES=$(python3 -c "import json; d=json.load(open('${LEVEL_JSON}')); print(len(d['zone_phases']))" 2>/dev/null || echo 0)
  if [ "$ZONES" -eq 4 ]; then
    ok "Zone phases: ${ZONES} (4 required)"
  else fail "Zone phases: ${ZONES} (4 required)"; fi
  
  # Check sectors
  SECTORS=$(python3 -c "import json; d=json.load(open('${LEVEL_JSON}')); print(len(d['sectors']))" 2>/dev/null || echo 0)
  if [ "$SECTORS" -eq 3 ]; then
    ok "Sectors: ${SECTORS} (3: ArmoryHub/ProvingGrounds/Park)"
  else fail "Sectors: ${SECTORS} (3 required)"; fi
  
else fail "Missing: CIGKV_level_data.json"; fi

# Check C++ Level Data Loader
if [ -f "${REPO_ROOT}/Unreal/KhaaosRun/Source/KhaaosRun/Game/Level/KhaaosCIGKVLevelData.h" ]; then
  ok "CIGKV Level Data Loader (.h) exists"
else fail "Missing: KhaaosCIGKVLevelData.h"; fi

if [ -f "${REPO_ROOT}/Unreal/KhaaosRun/Source/KhaaosRun/Game/Level/KhaaosCIGKVLevelData.cpp" ]; then
  ok "CIGKV Level Data Loader (.cpp) exists"
else fail "Missing: KhaaosCIGKVLevelData.cpp"; fi

# ─── Step 3: EOS Production Setup ───
echo ""
echo "━━━ Step 3: EOS Production Setup ━━━"

if [ -f "${REPO_ROOT}/scripts/build/setup_eos_production_full.sh" ]; then
  ok "EOS production setup script exists"
else fail "Missing: setup_eos_production_full.sh"; fi

for sub in auth lobby matchmaking sessions cloudsave regions; do
  if [ -f "${REPO_ROOT}/config/eos/eos_${sub}.json" ] || \
     [ -f "${REPO_ROOT}/config/eos/eos_${sub}1.json" ]; then
    ok "EOS ${sub} config template reference in script"
  else
    # Check if it's generated by the setup script
    if grep -q "eos_${sub}.json" "${REPO_ROOT}/scripts/build/setup_eos_production_full.sh" 2>/dev/null; then
      ok "EOS ${sub} config defined in setup script"
    else warn "EOS ${sub} config may be missing"; fi
  fi
done

# Check INI reference
if grep -q "DefaultEOS_Production.ini" "${REPO_ROOT}/scripts/build/setup_eos_production_full.sh" 2>/dev/null; then
  ok "EOS Production INI generated by setup script"
else fail "EOS Production INI not in setup script"; fi

# ─── Step 4: Asset Pipeline ───
echo ""
echo "━━━ Step 4: Asset Pipeline ━━━"

MANIFEST="${REPO_ROOT}/Content/Assets/asset_manifest.json"
if [ -f "${MANIFEST}" ]; then
  ok "Asset manifest exists"
  
  if python3 -c "import json; json.load(open('${MANIFEST}'))" 2>/dev/null; then
    ok "Asset manifest is valid JSON"
  else fail "Asset manifest JSON is invalid"; fi
  
  TOTAL=$(python3 -c "import json; d=json.load(open('${MANIFEST}')); print(d['summary']['total_assets'])" 2>/dev/null || echo 0)
  ok "Total assets in manifest: ${TOTAL}"
  
  WEAPONS=$(python3 -c "import json; d=json.load(open('${MANIFEST}')); print(len(d['weapons']))" 2>/dev/null || echo 0)
  ok "Weapons defined: ${WEAPONS}"
  
  LOOT_ITEMS=$(python3 -c "import json; d=json.load(open('${MANIFEST}')); print(len(d['loot_items']))" 2>/dev/null || echo 0)
  ok "Loot items defined: ${LOOT_ITEMS}"
  
else fail "Missing: asset_manifest.json"; fi

if [ -f "${REPO_ROOT}/scripts/build/import_assets.sh" ]; then
  ok "Asset import script exists"
else fail "Missing: import_assets.sh"; fi

# Check content directories
CONTENT="${REPO_ROOT}/Unreal/KhaaosRun/Content"
for dir in Characters Weapons Loot Environment VFX Audio Maps; do
  if [ -d "${CONTENT}/${dir}" ]; then
    ok "Content/${dir}/ directory exists"
  else fail "Missing: Content/${dir}/"; fi
done

# ─── Summary ───
TOTAL=$((PASS + FAIL + WARN))
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "  VERIFICATION RESULT"
echo "═══════════════════════════════════════════════════════════"
echo -e "  ${GREEN}PASS${NC}: ${PASS}"
echo -e "  ${RED}FAIL${NC}: ${FAIL}"
echo -e "  ${YELLOW}WARN${NC}: ${WARN}"
echo "  Total: ${TOTAL}"
echo "═══════════════════════════════════════════════════════════"

if [ $FAIL -eq 0 ]; then
  echo -e "  ${GREEN}BUILD-READY: All 4 steps verified!${NC}"
  echo ""
  echo "  Next: Provision GPU VM → run setup_ue5_full.sh → compile → CIGKV playable"
  exit 0
else
  echo -e "  ${RED}NOT BUILD-READY: ${FAIL} check(s) failed${NC}"
  exit 1
fi
